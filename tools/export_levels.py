"""Export the canonical Python maps for the dependency-free browser edition."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from levels import LEVELS

output = "// Generated by python tools/export_levels.py; edit levels.py.\nexport const LEVELS = "
output += json.dumps(LEVELS, indent=2) + ";\n"
target = ROOT / "docs/js/levels.js"
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != output:
        raise SystemExit("Browser maps are stale: run python tools/export_levels.py")
else:
    target.write_text(output, encoding="utf-8")
